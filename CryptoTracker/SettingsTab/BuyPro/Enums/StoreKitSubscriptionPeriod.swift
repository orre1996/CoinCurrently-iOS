enum StoreKitSubscriptionPeriod: String {
    case none
    case weekly = "Weekly"
    case monthly = "Monthly"
    case everyTwoMonths = "Every 2 months"
    case everyThreeMonths = "Every 3 months"
    case everySixMonths = "Every 6 months"
    case yearly = "Annual"
}
